def event_address(name: str) -> int:
    """Absolute WRAM byte address containing this event's bit."""
    return WEVENTFLAGS_BASE + EVENTS[name] // 8


def event_bit(name: str) -> int:
    """Bit position (0-7) within event_address(name)."""
    return EVENTS[name] % 8
